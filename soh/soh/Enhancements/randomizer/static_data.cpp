std::set<RandomizerCheck> StaticData::ParseExcludedLocations(const std::string& value) {
    std::set<RandomizerCheck> locations;
    std::stringstream tokens(value);
    std::string token;
    while (getline(tokens, token, ',')) {
        auto it = excludedLocationToEnum.find(token);
        if (it != excludedLocationToEnum.end()) {
            locations.insert(it->second);
        }
    }
    return locations;
}

std::string StaticData::SerializeExcludedLocations(const std::set<RandomizerCheck>& locations) {
    std::string value = "";
    for (RandomizerCheck rc : locations) {
        value += EnumToString(rc);
        value += ",";
    }
    return value;
}

